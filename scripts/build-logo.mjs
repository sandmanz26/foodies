// Builds the RIUH wordmark as real SVG paths from the display font,
// so the logo never depends on a webfont being loaded.
import opentype from 'opentype.js';
import { readFileSync, writeFileSync } from 'node:fs';

const buf = readFileSync('node_modules/@fontsource/bagel-fat-one/files/bagel-fat-one-latin-400-normal.woff');
const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));

const SIZE = 200;
// Each letter is knocked slightly off its seat: the name means "rowdy".
const letters = [
  { ch: 'R', rot: -7, dy: 6 },
  { ch: 'I', rot: 5, dy: -8 },
  { ch: 'U', rot: -4, dy: 8 },
  { ch: 'H', rot: 6, dy: -4 },
];
const TRACK = -6;

let x = 0;
const parts = [];
let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
for (const l of letters) {
  const g = font.charToGlyph(l.ch);
  const adv = (g.advanceWidth / font.unitsPerEm) * SIZE;
  const path = g.getPath(0, 0, SIZE);
  const bb = path.getBoundingBox();
  const cx = (bb.x1 + bb.x2) / 2, cy = (bb.y1 + bb.y2) / 2;
  const r = (l.rot * Math.PI) / 180;
  const cos = Math.cos(r), sin = Math.sin(r);
  // bake the transform into the path so the SVG is a flat list of paths
  for (const c of path.commands) {
    for (const [kx, ky] of [['x', 'y'], ['x1', 'y1'], ['x2', 'y2']]) {
      if (c[kx] === undefined) continue;
      const px = c[kx] - cx, py = c[ky] - cy;
      c[kx] = px * cos - py * sin + cx + x;
      c[ky] = px * sin + py * cos + cy + l.dy;
      minX = Math.min(minX, c[kx]); maxX = Math.max(maxX, c[kx]);
      minY = Math.min(minY, c[ky]); maxY = Math.max(maxY, c[ky]);
    }
  }
  parts.push({ ch: l.ch, d: path.toPathData(1) });
  x += adv + TRACK;
}
const pad = 4;
const vb = [minX - pad, minY - pad, maxX - minX + pad * 2, maxY - minY + pad * 2].map((n) => +n.toFixed(1));
const paths = parts.map((p) => `<path data-l="${p.ch}" d="${p.d}"/>`).join('');
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${vb.join(' ')}" fill="currentColor" role="img" aria-label="RIUH">${paths}</svg>`;
writeFileSync('docs/assets/riuh-wordmark.svg', svg);
writeFileSync('src/brand/wordmark.js', `// generated by scripts/build-logo.mjs\nexport const WORDMARK_VIEWBOX = '${vb.join(' ')}';\nexport const WORDMARK_PATHS = ${JSON.stringify(parts)};\n`);
console.log('wordmark', vb.join(' '), svg.length, 'bytes');
